#include <stdio.h>
#include <stdlib.h>
#include <unistd.h>
#include <sys/wait.h>

// Программа демонстрирует связку системных вызовов fork() и exec().
// Она создает процесс-потомок, который полностью заменяет свой исполняемый код
// на код ранее скомпилированной программы sequential_min_max.
int main(int argc, char **argv) {
    // Создаем клон текущего процесса
    pid_t pid = fork();

    if (pid == 0) {
        // Код выполняется внутри дочернего процесса.
        // Подготавливаем массив аргументов. По правилам ОС, первый аргумент (индекс 0) 
        // всегда должен содержать имя вызываемой программы. Последний аргумент - NULL.
        char *args[] = {"./sequential_min_max", "42", "1000", NULL};
        
        // execv загружает новый исполняемый файл в память текущего процесса,
        // уничтожая предыдущую программу. Процесс продолжает жить под тем же PID, 
        // но выполняет уже совершенно другой код.
        execv("./sequential_min_max", args);
        
        perror("Ошибка при вызове execv. Убедитесь, что sequential_min_max скомпилирован");
        return 1;
    } else if (pid > 0) {
        // Код выполняется внутри родительского процесса.
        // Родитель обязан дождаться завершения ребенка, иначе ребенок может 
        // превратиться в процесс-зомби, занимающий ресурсы в таблице процессов ОС.
        wait(NULL);
    } else {
        perror("Ошибка при вызове fork");
        return 1;
    }

    return 0;
}